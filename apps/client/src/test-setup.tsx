import '@repo/i18n';

import { configureApiClient } from '@repo/api-client';
import {
  getContactMock,
  getFeatureFlagMock,
  getProjectMock,
  getResumeMock,
} from '@repo/api-client/mocks';
import i18n from 'i18next';
import type { ReactNode } from 'react';
import { setupServer } from 'msw/node';

import { loadConfig } from './config/config.js';

// Components render `Link`s outside of a router: plain anchors, path parameters substituted.
vi.mock('@tanstack/react-router', () => ({
  Link: ({
    children,
    to,
    params,
    className,
  }: {
    children?: ReactNode;
    to?: string;
    params?: Record<string, string>;
    className?: string;
  }) => (
    <a
      href={(to ?? '').replace(/\$(\w+)/g, (_, name: string) => params?.[name] ?? '')}
      className={className}
    >
      {children}
    </a>
  ),
}));

/** API calls are answered by the MSW handlers generated by orval. */
export const server = setupServer(
  ...getContactMock(),
  ...getFeatureFlagMock(),
  ...getProjectMock(),
  ...getResumeMock(),
);

// The configuration `/config.js` gives the application: no reCAPTCHA, no analytics.
window.__APP_CONFIG__ = {
  apiUrl: 'http://api.test',
  recaptchaSiteKey: '',
  umami: { src: '', websiteId: '' },
};
configureApiClient({ baseUrl: loadConfig().apiUrl });

beforeAll(async () => {
  server.listen({ onUnhandledRequest: 'error' });
  // French in tests: jsdom's navigator.language is `en`.
  await i18n.changeLanguage('fr');
});
afterEach(() => server.resetHandlers());
afterAll(() => server.close());
